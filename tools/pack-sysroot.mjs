// Packs the wcc compiler (cc.wasm) and its sysroot (headers + libs) into generated modules
// that are bundled into the page (no runtime fetch needed). Source: vendor/wcc, built from
// tyfkda/xcc with vendor/wcc/xcc-stumperz.patch applied.
import fs from 'node:fs';
import path from 'node:path';
const src = path.resolve('vendor/wcc');
const dst = path.resolve('src/runtime/generated');
fs.mkdirSync(dst, { recursive: true });
const out = {};
function walk(dir, prefix) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    const v = `${prefix}/${e.name}`;
    if (e.isDirectory()) walk(p, v);
    else out[v] = fs.readFileSync(p).toString('base64');
  }
}
walk(path.join(src, 'include'), 'usr/include');
walk(path.join(src, 'lib'), 'usr/lib');
fs.writeFileSync(path.join(dst, 'sysroot.json'), JSON.stringify(out));
const wasm = fs.readFileSync(path.join(src, 'cc.wasm')).toString('base64');
fs.writeFileSync(path.join(dst, 'cc-wasm.ts'), `// Generated by tools/pack-sysroot.mjs — do not edit.\nexport const CC_WASM_BASE64 = '${wasm}';\n`);
console.log(Object.keys(out).length, 'sysroot files packed,', Math.round(wasm.length / 1024), 'KiB of base64 compiler');
